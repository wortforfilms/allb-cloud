#!/usr/bin/env node
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const spec = JSON.parse(await readFile(resolve(root, "contracts/ecosystem-contract.json"), "utf8"));
const check = process.argv.includes("--check");
const quoted = values => values.map(value => JSON.stringify(value)).join(" | ");

const typescript = `// Generated by scripts/generate-contracts.mjs. Do not edit.\n` +
`export const SCHEMA_VERSION = ${JSON.stringify(spec.schemaVersion)} as const;\n` +
`export type AssuranceLevel = ${quoted(spec.assuranceLevels)};\n` +
`export type Effect = ${quoted(spec.effects)};\n` +
`export type ProtectedAction = ${quoted(spec.protectedActions)};\n` +
`export type ExecutionMode = ${quoted(spec.executionModes)};\n` +
`export type ExecutionStatus = ${quoted(spec.executionStatuses)};\n` +
`export type RuntimeOperation =\n  | { kind: "tokenizeBrahmi"; text: string }\n  | { kind: "evaluateSandhi"; left: string; right: string }\n  | { kind: "lookupSutra"; sutraId: string };\n` +
`export interface OperationRequest { schemaVersion: typeof SCHEMA_VERSION; requestId: string; principal: string; action: ProtectedAction; resource: string; workspace: string; assurance: AssuranceLevel; operation?: RuntimeOperation; }\n` +
`export interface AuthorizationDecision { effect: Effect; reasons: string[]; policy_version: string; policy_digest: string; request_hash: string; }\n` +
`export interface RuntimeCapability { id: string; available: boolean; mode: ExecutionMode; detail: string; }\n` +
`export interface ExecutionResult { schema_version: string; operation_id: string; request_id: string; runtime_version: string; execution_mode: ExecutionMode; status: ExecutionStatus; input_digest: string; output_digest: string; output: unknown; duration_micros: number; }\n` +
`export interface EvidenceEvent { id: string; request_id: string; principal: string; action: ProtectedAction; resource: string; workspace: string; assurance: AssuranceLevel; decision: Effect; reasons: string[]; policy_version: string; policy_digest: string; request_hash: string; event_hash: string; previous_event_hash: string | null; schema_version: number; created_at: string; }\n` +
`export interface ExecutionEvidence { id: string; authorization_event_id: string; request_id: string; operation_id: string; status: ExecutionStatus; execution_mode: ExecutionMode; input_digest: string; output_digest: string; event_hash: string; created_at: string; }\n` +
`export interface GovernedOperationResult { authorization: EvidenceEvent; execution: ExecutionResult | null; execution_evidence: ExecutionEvidence | null; }\n` +
`export const PROTECTED_ACTIONS = ${JSON.stringify(spec.protectedActions)} as const;\n`;

const python = `# Generated by scripts/generate-contracts.mjs. Do not edit.\n` +
`from dataclasses import dataclass\nfrom enum import Enum\nfrom typing import Any, Optional\n\n` +
`SCHEMA_VERSION = ${JSON.stringify(spec.schemaVersion)}\n\n` +
`class AssuranceLevel(str, Enum):\n${spec.assuranceLevels.map((v,i)=>`    VALUE_${i} = ${JSON.stringify(v)}`).join("\n")}\n\n` +
`class ProtectedAction(str, Enum):\n${spec.protectedActions.map((v,i)=>`    VALUE_${i} = ${JSON.stringify(v)}`).join("\n")}\n\n` +
`class ExecutionMode(str, Enum):\n${spec.executionModes.map(v=>`    ${v.toUpperCase()} = ${JSON.stringify(v)}`).join("\n")}\n\n` +
`class ExecutionStatus(str, Enum):\n${spec.executionStatuses.map(v=>`    ${v.toUpperCase()} = ${JSON.stringify(v)}`).join("\n")}\n\n` +
`@dataclass(frozen=True)\nclass RuntimeOperation:\n    kind: str\n    payload: dict[str, Any]\n\n` +
`@dataclass(frozen=True)\nclass OperationRequest:\n    schema_version: str\n    request_id: str\n    principal: str\n    action: ProtectedAction\n    resource: str\n    workspace: str\n    assurance: AssuranceLevel\n    operation: Optional[RuntimeOperation] = None\n`;

const schema = JSON.stringify({
  $schema: "https://json-schema.org/draft/2020-12/schema",
  title: "Siddham OperationRequest",
  type: "object",
  additionalProperties: false,
  required: ["schemaVersion","requestId","principal","action","resource","workspace","assurance"],
  properties: {
    schemaVersion: { const: spec.schemaVersion }, requestId: { type:"string", minLength:1 }, principal:{type:"string",minLength:1},
    action:{enum:spec.protectedActions}, resource:{type:"string",minLength:1}, workspace:{type:"string",minLength:1}, assurance:{enum:spec.assuranceLevels},
    operation:{ oneOf:[
      {type:"object",additionalProperties:false,required:["kind","text"],properties:{kind:{const:"tokenizeBrahmi"},text:{type:"string"}}},
      {type:"object",additionalProperties:false,required:["kind","left","right"],properties:{kind:{const:"evaluateSandhi"},left:{type:"string",minLength:1},right:{type:"string",minLength:1}}},
      {type:"object",additionalProperties:false,required:["kind","sutraId"],properties:{kind:{const:"lookupSutra"},sutraId:{type:"string",pattern:"^\\\\d+\\\\.\\\\d+\\\\.\\\\d+$"}}}
    ]}
  }
}, null, 2) + "\n";

const outputs = new Map([
  ["generated/typescript/contracts.ts", typescript],
  ["services/edge_worker/src/generated/contracts.ts", typescript],
  ["apps/siddham-authority-desktop/src/generated/contracts.ts", typescript],
  ["generated/python/siddham_contracts.py", python],
  ["contracts/generated/operation-request.schema.json", schema],
]);

let drift = false;
for (const [relative, content] of outputs) {
  const path = resolve(root, relative);
  if (check) {
    const current = await readFile(path, "utf8").catch(() => "");
    const normalizedCurrent = current.replaceAll("\r\n", "\n");
    if (normalizedCurrent !== content) { console.error(`contract drift: ${relative}`); drift = true; }
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
    console.log(`generated ${relative}`);
  }
}
if (drift) process.exit(1);
