#!/usr/bin/env python3
"""Reference model and test vectors for the Paninian datapath (hardware/rtl/panini_*.v).

This is an independent implementation in Python, written from the sutras rather than
from the Verilog. It writes two vector files for hardware/tb/panini_tb.v:

  hardware/tb/vectors/panini_ref.mem   all 13 x 13 vowel pairs, inside a word and at a
                                       word boundary (338 cases): rule, result, 8.3.19 option
  hardware/tb/vectors/vidyut.mem       Vidyut's own word-boundary vowel sandhi results
                                       (hardware/tb/vectors/vidyut_vowel_sandhi.tsv, MIT),
                                       for every pair both models cover

It also checks the reference itself against Vidyut and stops if they disagree.
Run: python3 hardware/scripts/panini_ref.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
VEC = os.path.join(os.path.dirname(HERE), "tb", "vectors")

# Phoneme codes: must match hardware/rtl/panini_defs.vh
VOWELS = ["a", "A", "i", "I", "u", "U", "f", "F", "x", "X", "e", "E", "o", "O"]   # SLP1, codes 0..13
CODE = {v: i for i, v in enumerate(VOWELS)}
CODE.update({"y": 15, "v": 16, "r": 17, "l": 18})
NONE = 63
RULES = {None: 0, "6.1.77": 1, "6.1.78": 2, "6.1.87": 3, "6.1.88": 4, "6.1.101": 5, "6.1.109": 6}

STHANA = {"a": 0, "A": 0, "i": 1, "I": 1, "f": 2, "F": 2, "x": 3, "X": 3, "u": 4, "U": 4, "e": 5, "E": 5, "o": 6, "O": 6}
AC = set(VOWELS)                                  # अच् (with long forms, 1.1.69)
IK = set("iIuUfFxX")                              # इक्
EC = set("eEoO")                                  # एच्
AK = set("aAiIuUfFxX")                            # अक्
ENG = set("eo")                                   # एङ्
AT = set("aA")                                    # आत्
TESTED = [v for v in VOWELS if v != "X"]          # the 13 vowels the testbench sweeps
DIRGHA = {"a": "A", "i": "I", "u": "U", "f": "F", "x": "X"}
DIRGHA.update({v: v for v in "AIUFX"})
YAN = {1: "y", 4: "v", 2: "r", 3: "l"}
GUNA = {0: "a", 1: "e", 5: "e", 4: "o", 6: "o", 2: "ar", 3: "al"}


def phase1(l, r, pada_end):
    """Which sutra applies at the juncture l + r, and the result (string of SLP1 sounds, avagraha)."""
    matches = set()
    if l in IK and r in AC: matches.add("6.1.77")
    if l in EC and r in AC: matches.add("6.1.78")
    if l in AT and r in AC: matches.add("6.1.87")             # आद्गुणः, अचि from 6.1.77
    if l in AT and r in EC: matches.add("6.1.88")
    if l in AK and r in AK and STHANA[l] == STHANA[r]: matches.add("6.1.101")
    if pada_end and l in ENG and r == "a": matches.add("6.1.109")
    # apavāda (exception) beats utsarga (general rule)
    exceptions = {"6.1.101": {"6.1.77", "6.1.87"}, "6.1.88": {"6.1.87"}, "6.1.109": {"6.1.78"}}
    left = set(matches)
    for exc, gens in exceptions.items():
        if exc in matches:
            left -= gens
    assert len(left) <= 1, (l, r, left)
    if not left:
        return None, l + r, False
    rule = left.pop()
    if rule == "6.1.77": return rule, YAN[STHANA[l]] + r, False
    if rule == "6.1.78": return rule, {"e": "ay", "o": "av", "E": "Ay", "O": "Av"}[l] + r, False
    if rule == "6.1.87": return rule, GUNA[STHANA[r]], False
    if rule == "6.1.88": return rule, "E" if STHANA[r] == 5 else "O", False
    if rule == "6.1.101": return rule, DIRGHA[l], False
    if rule == "6.1.109": return rule, l, True


def tripadi(seq, pada_end):
    """8.3.19 लोपः शाकल्यस्य (optional): pada-final y/v after a/ā before a vowel is lost."""
    if pada_end and len(seq) == 3 and seq[0] in AT and seq[1] in "yv" and seq[2] in AC:
        return seq[0] + seq[2]
    return None


def codes(seq, n=3):
    c = [CODE[ch] for ch in seq]
    return c + [NONE] * (n - len(c))


def main():
    os.makedirs(VEC, exist_ok=True)
    ref = []
    for pada_end in (0, 1):
        for l in TESTED:
            for r in TESTED:
                rule, seq, avg = phase1(l, r, pada_end)
                alt = tripadi(seq, pada_end)
                ref.append((l, r, pada_end, rule, seq, avg, alt))
    with open(os.path.join(VEC, "panini_ref.mem"), "w") as f:
        f.write("// left right pada_end rule len o0 o1 o2 avagraha alt_valid alt_len a0 a1 a2  (hex; generated by hardware/scripts/panini_ref.py)\n")
        for l, r, pe, rule, seq, avg, alt in ref:
            row = [CODE[l], CODE[r], pe, RULES[rule], len(seq), *codes(seq), int(avg), int(alt is not None), len(alt or ""), *codes(alt or "")]
            f.write(" ".join(f"{x:02x}" for x in row) + "\n")

    # Vidyut golden vectors (word boundary), and check the reference against them
    tsv = os.path.join(VEC, "vidyut_vowel_sandhi.tsv")
    gold, bad = [], []
    for line in open(tsv, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        l, r, result = line.rstrip("\n").split("\t")
        if l not in TESTED or r not in TESTED:
            continue
        seq, avg = result.replace(" ", "").replace("'", ""), "'" in result
        rule, mine, mavg = phase1(l, r, 1)
        alt = tripadi(mine, 1)
        if (seq, avg) not in {(mine, mavg), (alt, False)}:
            bad.append((l, r, result, mine, alt))
        gold.append((l, r, seq, avg))
    if bad:
        sys.exit(f"Reference disagrees with Vidyut on {len(bad)} pairs, for example {bad[:5]}")
    with open(os.path.join(VEC, "vidyut.mem"), "w") as f:
        f.write("// left right len s0 s1 s2 avagraha  (hex; Vidyut generate_rules(), word boundary)\n")
        for l, r, seq, avg in gold:
            f.write(" ".join(f"{x:02x}" for x in [CODE[l], CODE[r], len(seq), *codes(seq), int(avg)]) + "\n")
    print(f"panini_ref.mem: {len(ref)} cases · vidyut.mem: {len(gold)} cases · reference agrees with Vidyut on all {len(gold)}")
    with open(os.path.join(VEC, "counts.vh"), "w") as f:
        f.write(f"`define PANINI_REF_CASES {len(ref)}\n`define PANINI_VIDYUT_CASES {len(gold)}\n")


if __name__ == "__main__":
    main()
